  const pending = before.actions.filter(action => action.payload.name === "mobile charge" && action.status === "proposed").at(-1);
  expect(pending).toBeTruthy();
  await chat(page).getByRole("button", { name: "Check and retry this turn", exact: true }).click();
  await expect(review(page)).toBeVisible();
  expect(submissions).toHaveLength(2); expect(submissions[1]).toEqual(submissions[0]);
  await page.reload();
  await expect(review(page)).toBeVisible();
  const after = await (await page.request.get("/__test/state")).json();
  expect(after.actions.filter(action => action.id === pending.id)).toHaveLength(1);
  expect(after.creates).toBe(before.creates);
