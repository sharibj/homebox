async function done(page) { await confirmation(page).getByRole("button", { name: "Done", exact: true }).click(); }
async function cancel(page) {
  await confirmation(page).getByRole("button", { name: "Cancel change" }).click();
  await expect(confirmation(page)).toContainText("Change cancelled");
  await done(page);
}
async function state(request) { return (await request.get("/__test/state")).json(); }
async function capture(page, hint = "") {
  await page.getByLabel("Take or choose a photo").setInputFiles(photo);
  if (hint) await page.getByLabel("Optional hint").fill(hint);
  await page.getByRole("button", { name: "Suggest details from photo" }).click();
}
