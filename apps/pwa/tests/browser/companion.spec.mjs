test("review includes all photo metadata; cancel/review reuses capture; remove photo detaches it", async ({ page, request }) => {
  await login(page);
  await page.getByRole("button", { name: "Add an item", exact: true }).click();
  await capture(page);
  await expect(page.getByRole("heading", { name: "Possible duplicates" })).toBeVisible();
  await page.getByLabel("Item name", { exact: true }).fill("Reviewed enamel mug");
  await page.getByLabel("Location", { exact: true }).selectOption(garage);
  await page.getByLabel("Quantity", { exact: true }).fill("3");
  await page.getByLabel("Manufacturer", { exact: true }).fill("Reviewed maker");
  await page.getByLabel("Model", { exact: true }).fill("Trail mug");
  await page.getByLabel("Visible serial number").fill("SERIAL-123");
  await page.getByLabel("Tags, separated by commas", { exact: true }).fill("camping, reviewed");
  await page.getByLabel("Notes", { exact: true }).fill("Blue enamel, checked by me");
  const initial = await state(request);
  const proposed = page.waitForRequest(req => req.url().endsWith("/actions") && req.method() === "POST");
  await page.getByRole("button", { name: "Review new item" }).click();
  const first = (await proposed).postDataJSON();
  expect(first.captureId).toBeTruthy();
  await expect(confirmation(page)).toContainText("Reviewed maker");
  for (const value of ["Trail mug", "SERIAL-123", "Blue enamel, checked by me", "camping, reviewed", "Garage / Camping shelf", "Photo included"]) await expect(confirmation(page)).toContainText(value);
  await expect(confirmation(page).getByRole("img", { name: "Reviewed photo to attach" })).toBeVisible();
  expect((await state(request)).creates).toBe(initial.creates);
  await page.screenshot({ path: "/results/photo-review-mobile.png", fullPage: true });
  await cancel(page);
  await expect(page.getByLabel("Item name", { exact: true })).toHaveValue("Reviewed enamel mug");
  await page.getByLabel("Item name", { exact: true }).fill("Reviewed enamel mug edited");
  const reproposed = page.waitForRequest(req => req.url().endsWith("/actions") && req.method() === "POST");
  await page.getByRole("button", { name: "Review new item" }).click();
  expect((await reproposed).postDataJSON().captureId).toBe(first.captureId);
  await cancel(page);
  await page.getByRole("button", { name: "Remove photo" }).click();
  await expect(page.getByRole("img", { name: "Selected item photo preview" })).toHaveCount(0);
  await expect(page.getByLabel("Item name", { exact: true })).toHaveValue("Reviewed enamel mug edited");
  const detached = page.waitForRequest(req => req.url().endsWith("/actions") && req.method() === "POST");
  await page.getByRole("button", { name: "Review new item" }).click();
  expect((await detached).postDataJSON()).not.toHaveProperty("captureId");
  await expect(confirmation(page).getByRole("img", { name: "Reviewed photo to attach" })).toHaveCount(0);
  await confirmation(page).getByRole("button", { name: "Confirm change" }).click();
  await expect(confirmation(page)).toContainText("Saved to Homebox");
  expect((await state(request)).creates).toBe(initial.creates + 1);
});
