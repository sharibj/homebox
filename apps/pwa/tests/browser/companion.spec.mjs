test("another tab switching collection never redirects a stale create into the new collection", async ({ page, context, request }) => {
  await login(page);
  await page.getByRole("button", { name: "Add an item", exact: true }).click();
  await page.getByLabel("Item name", { exact: true }).fill("Must not cross collections");
  const second = await context.newPage();
  await second.goto("/");
  await second.getByLabel("Collection", { exact: true }).selectOption(workshop);
  await expect(second.getByRole("heading", { name: "Workshop", exact: true })).toBeVisible();
  const initial = await state(request);
  const rejected = page.waitForResponse(response => response.url().endsWith("/actions") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Review new item" }).click();
  expect((await rejected).status()).toBe(409);
  await expect(page.getByRole("alert")).toContainText("collection changed in another tab");
  await expect(page.getByRole("heading", { name: "Workshop", exact: true })).toBeVisible();
  await expect(page.getByLabel("Item name", { exact: true })).toHaveValue("");
  await expect(confirmation(page)).toHaveCount(0);
  expect((await state(request)).creates).toBe(initial.creates);
  await second.close();
});
