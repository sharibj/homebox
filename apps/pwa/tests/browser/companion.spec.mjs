test("offline reload shows only public shell, no cached private API inventory or browser tokens", async ({ page, context }) => {
  await login(page);
  await page.getByRole("searchbox", { name: "Search inventory" }).fill("Camping");
  await page.getByRole("button", { name: "Search", exact: true }).click();
  await expect(page.getByRole("heading", { name: "1 result", exact: true })).toBeVisible();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.goto("/");
  const cacheEntries = await page.evaluate(async () => {
    const keys = await caches.keys();
    const requests = await Promise.all(keys.map(async key => (await (await caches.open(key)).keys()).map(request => request.url)));
    return requests.flat();
  });
  expect(cacheEntries.some(url => url.includes("/api/"))).toBe(false);
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
  expect(await page.evaluate(() => Object.keys(sessionStorage))).toEqual([]);
  await context.setOffline(true);
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Welcome home", exact: true })).toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "You’re offline" })).toBeVisible();
  await expect(page.getByText("Camping stove", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: "/results/offline-shell-mobile.png", fullPage: true });
});
