  const actionUrl = page.url();
  const initial = await state(request);
  await page.route("**/actions/*/confirm", async route => { await route.fetch(); await route.abort("failed"); });
  await confirmation(page).getByRole("button", { name: "Confirm change" }).click();
  await expect(confirmation(page)).toContainText("Check before trying again");
